const dictionaries: Record<Language, Dict> = { uz, ru, en, ko, ar };

/** Tarjima; `{n}`, `{name}` kabi o'rinlarni `vars` bilan to'ldiradi. */
export function translate(lang: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  const text = dictionaries[lang][key] ?? uz[key];
  return vars ? text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : text;
}

